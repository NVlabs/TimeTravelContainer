# Sizes of the scalars that the protocol has, in memory.
SCALAR_SIZES = {
    'uint8_t': 1,
    'uint16_t': 2,
    'uint32_t': 4,
    'int32_t': 4,
    'float': 4,
    'uint64_t': 8,
    'int64_t': 8,
    'double': 8,
    'size_t': 8,
    'char': 1,
}

# Go types of scalars, for loading them.
SCALAR_GO_TYPES = {
    'uint8_t': 'uint8',
    'uint16_t': 'uint16',
    'uint32_t': 'uint32',
    'int32_t': 'int32',
    'float': 'float32',
    'uint64_t': 'uint64',
    'int64_t': 'int64',
    'double': 'float64',
    'size_t': 'uint64',
    'char': 'int8',
}

LOOP_ITERS = 'ijklmn'


class Writer:
    """Collects lines of Go, indenting them by their braces."""

    def __init__(self):
        self.lines = []
        self.depth = 0

    def __call__(self, line=''):
        s = line.strip()
        code = s.split('//')[0].strip()
        label = code.startswith('case ') or code == 'default:'
        if code.startswith('}') or label:
            self.depth -= 1
        self.lines.append('\t' * self.depth + s if s else '')
        if code.endswith('{') or label:
            self.depth += 1

    def extend(self, other):
        for line in other.lines:
            self.lines.append('\t' * self.depth + line if line else '')

    def text(self):
        return '\n'.join(self.lines) + '\n'


class Level:
    """A level of the loops that reach a variable's elements."""

    def __init__(self, count, cstring=False):
        # count is a Go expression of the level's element count, or None for
        # a C string.
        self.count = count
        self.cstring = cstring


class Container:
    """How generated code reaches the variables of a struct, union, or
    command's arguments."""

    def __init__(self, gg, ty, typed):
        self.gg = gg
        self.ty = ty
        # typed is the name of a typed pointer to the container, or None for
        # a union, whose members are at its start, val.
        self.typed = typed

    def field(self, var):
        return '%s.%s' % (self.typed, self.gg.go_field(self.ty, var.name))

    def addr(self, var):
        if self.typed:
            return 'unsafe.Pointer(&%s)' % self.field(var)
        return 'val'

    def value(self, var):
        """The value of a pointer variable."""
        if self.typed:
            return self.field(var)
        return 'loadPointer(val)'

    def store(self, var, expr):
        if self.typed:
            return '%s = %s' % (self.field(var), expr)
        return 'storePointer(val, %s)' % expr


class GoGen:
    """Emits Go by the rules of venus-protocol's Gen for the renderer."""

    def __init__(self, vp, VkType, gen, consts):
        self.vp = vp
        self.VkType = VkType
        self.gen = gen
        self.reg = gen.reg
        self.consts = consts
        self.enum_values = {}
        for ty in self.reg.type_table.values():
            if ty.category == VkType.ENUM and ty.enums and ty.enums.values:
                for k, v in ty.enums.values.items():
                    self.enum_values[k] = v
        self._handles_memo = {}
        self._self_handles_memo = {}
        # replaced_commands are the commands that have handles to replace.
        self.replaced_commands = set()

    # Names and types.

    def go_field(self, ty, name):
        """The name that cgo -godefs gives a field of a struct, or of a
        command's arguments."""
        names = [v.name for v in ty.variables]
        if ty.category == self.VkType.COMMAND and ty.ret:
            names.append('ret')
        prefix = godefs_prefix(names)
        if name != prefix:
            name = name[len(prefix):] if name.startswith(prefix) else name
        return godefs_upper(name)

    def enum_value(self, name):
        v = self.enum_values[name]
        while v in self.enum_values:
            v = self.enum_values[v]
        return int(v, 0)

    def const(self, expr):
        """Resolves Vulkan's API constants in a C expression."""
        def sub(m):
            name = m.group(0)
            if name in self.consts:
                return str(self.consts[name])
            return str(self.enum_value(name))
        return re.sub(r'\bVK_[A-Z0-9_]+\b', sub, expr)

    def prim(self, ty):
        """The primitive of a scalar type."""
        ty = ty.base
        VkType = self.VkType
        if ty.category in (VkType.BITMASK, VkType.BASETYPE):
            return self.prim(ty.typedef)
        if ty.category == VkType.ENUM:
            return 'int32_t' if ty.enums.bitwidth == 32 else 'uint64_t'
        if ty.category == VkType.DEFAULT and ty.name in SCALAR_SIZES:
            return ty.name
        raise ValueError('%s is not a scalar' % ty.name)

    def is_scalar(self, ty):
        VkType = self.VkType
        return ty.base.category in (VkType.DEFAULT, VkType.BASETYPE, VkType.ENUM, VkType.BITMASK)

    def elem_size(self, ty):
        """A Go expression of the size of a base type."""
        ty = ty.base
        VkType = self.VkType
        if ty.category in (VkType.STRUCT, VkType.UNION):
            return 'unsafe.Sizeof(%s{})' % ty.name
        if ty.category == VkType.HANDLE:
            return '8'
        if ty.name == 'void':
            return '1'
        return str(SCALAR_SIZES[self.prim(ty)])

    def objtype(self, ty):
        name = ty.base.attrs['c_objtype']
        return '%d /* %s */' % (self.enum_value(name), name)

    def s_type(self, ty):
        return '%d /* %s */' % (self.enum_value(ty.s_type), ty.s_type)

    # Which types have handles to replace.

    def self_has_handles(self, ty):
        """Whether a struct's or union's own members have handles."""
        ty = ty.base
        if ty.name in self._self_handles_memo:
            return self._self_handles_memo[ty.name]
        self._self_handles_memo[ty.name] = False
        found = False
        for var in ty.variables:
            if var.is_p_next():
                continue
            if not self.gen.is_serializable(var):
                continue
            if self.needs_replace(var.ty.base):
                found = True
                break
        self._self_handles_memo[ty.name] = found
        return found

    def needs_replace(self, ty):
        """Whether replacing a type's handles does anything."""
        ty = ty.base
        VkType = self.VkType
        if ty.category == VkType.HANDLE:
            return True
        if not ty.might_contain_handle():
            return False
        if ty.name in self._handles_memo:
            return self._handles_memo[ty.name]
        self._handles_memo[ty.name] = False
        found = self.self_has_handles(ty)
        if not found and ty.category == VkType.STRUCT and ty.s_type:
            next_types, _ = self.gen.get_chain(ty)
            found = any(self.self_has_handles(n) for n in next_types)
        self._handles_memo[ty.name] = found
        return found

    # Loops.

    def len_value(self, ty, cont, name):
        """A Go expression of the uint64 that len name refers to."""
        if '[i].' in name:
            # ppBuildRangeInfos and ppMaxPrimitiveCounts: pInfos[i].geometryCount.
            arr_name, member = name.split('[i].')
            arr = ty.find_variables(arr_name)[0]
            return 'uint64((*%s)(elem(%s, i, %s)).%s)' % (
                arr.ty.base.name, cont.value(arr), self.elem_size(arr.ty.base),
                self.go_field(arr.ty.base, member))
        loop_vars = ty.find_variables(name)
        assert 1 <= len(loop_vars) <= 2, (ty.name, name)
        if len(loop_vars) == 1:
            lv = loop_vars[0]
            if lv.ty.is_pointer():
                return 'load_%s(%s)' % (self.prim(lv.ty.base), cont.value(lv))
            return 'uint64(%s)' % cont.field(lv)
        a, b = loop_vars
        assert a.ty.is_pointer() and not b.ty.is_pointer()
        return ('func() uint64 { if p := (*%s)(%s); p != nil { return uint64(p.%s) }; return 0 }()'
                % (a.ty.base.name, cont.value(a), self.go_field(a.ty.base, b.name)))

    def levels(self, ty, var, cont):
        """The loops that reach a variable's elements, as vn_protocol's
        VariableInfo._init_loop_info builds them, and the count of its
        dynamic array, if it is one."""
        levels = []
        if 'wa_require_static_len' in var.attrs or 'len_exprs' not in var.attrs:
            if var.ty.is_static_array():
                levels.append(Level(self.const(var.ty.static_array_size())))
            return levels, None
        for expr, name in zip(var.attrs['len_exprs'], var.attrs['len_names']):
            if expr == 'null-terminated':
                levels.append(Level(None, cstring=True))
            elif name:
                value = self.len_value(ty, cont, name)
                levels.append(Level(self.const(expr.replace(name, value))))
            else:
                levels.append(Level(self.const(expr)))
        dynamic_size = None
        if var.is_dynamic_array() and not var.ty.is_c_string():
            dynamic_size = levels[0].count
        return levels, dynamic_size

    def unroll(self, var, levels):
        """Pops the innermost level of a scalar array, which is
        (de)serialized at once, as VariableInfo._unroll_loop does."""
        VkType = self.VkType
        if levels and var.ty.base.category in (VkType.DEFAULT, VkType.BASETYPE, VkType.ENUM):
            return levels.pop()
        return None

    def array_stem(self, var):
        if var.is_blob():
            return 'blob'
        if var.ty.base.name == 'char':
            return 'char'
        return self.prim(var.ty.base)

    def elem_size_at(self, var, level):
        """The size of the elements of a variable's array at a level."""
        if level < var.ty.indirection_depth() - 1:
            return '8'
        return self.elem_size(var.ty.base)

    # Decoding.

    def validity(self, ty, var, initialized):
        return self.gen._get_variable_validity(ty, var, initialized)

    def decode_call(self, var, validity, addr):
        VI = self.vp.Gen.VariableInfo
        VkType = self.VkType
        base = var.ty.base
        if base.category == VkType.HANDLE:
            if validity == VI.VALID:
                return 'decode_handle_lookup(d, %s, %s)' % (addr, self.objtype(base))
            return 'decode_handle(d, %s)' % addr
        if base.category in (VkType.STRUCT, VkType.UNION):
            suffix = '_partial' if validity == VI.PARTIAL and base.category == VkType.STRUCT else ''
            return 'decode_%s%s_temp(d, %s)' % (base.name, suffix, addr)
        return 'decode_%s(d, %s)' % (self.prim(base), addr)

    def decode_var(self, w, ty, var, cont, validity):
        """Emits the decoding of a member or argument, as
        Gen._decode_variable_info and Gen._decode_variable do with
        alloc_storage."""
        VI = self.vp.Gen.VariableInfo
        is_ptr = var.ty.is_pointer()
        if validity == VI.INVALID and not is_ptr:
            w('// skip %s' % var.name)
            return
        levels, dynamic_size = self.levels(ty, var, cont)

        body = Writer()
        if not self.gen.is_serializable(var):
            assert var.maybe_null() or ty.name in self.vp.Gen.UNION_DEFAULT_TAGS
            body('d.SetFatal()')
        else:
            self.decode_body(body, ty, var, cont, validity, levels)

        if var.is_dynamic_array():
            w('if peek_array_size(d) != 0 {')
            w.extend(body)
            w('} else {')
            if not var.is_optional() and var.can_validate() and dynamic_size:
                w('decode_array_size(d, %s)' % dynamic_size)
            else:
                w('decode_array_size_unchecked(d)')
            w(cont.store(var, 'nil'))
            w('}')
        elif is_ptr:
            w('if decode_simple_pointer(d) {')
            w.extend(body)
            w('} else {')
            w(cont.store(var, 'nil'))
            if not var.is_optional() and var.can_validate():
                w('d.SetFatal()')
            w('}')
        elif len(body.lines) > 1:
            w('{')
            w.extend(body)
            w('}')
        else:
            w.extend(body)

    def decode_body(self, w, ty, var, cont, validity, levels):
        VI = self.vp.Gen.VariableInfo
        is_ptr = var.ty.is_pointer()
        unrolled = self.unroll(var, levels)
        container = None if is_ptr else cont.addr(var)

        def allocate(level, alloc_expr):
            p = 'p%d' % level
            w('%s := %s' % (p, alloc_expr))
            if level == 0:
                w(cont.store(var, p))
            else:
                w('storePointer(elem(p%d, %s, 8), %s)' % (level - 1, LOOP_ITERS[level - 1], p))
            w('if %s == nil {' % p)
            w('return')
            w('}')
            return p

        for k, lvl in enumerate(levels):
            assert not lvl.cstring
            count = 'iter_count' if k == 0 else 'iter_count_' + LOOP_ITERS[k]
            w('%s := decode_array_size(d, %s)' % (count, lvl.count))
            if is_ptr:
                container = allocate(k, 'd.AllocTempArray(%s, %s)' % (self.elem_size_at(var, k), count))
            w('for %s := uint64(0); %s < %s; %s++ {' % (LOOP_ITERS[k], LOOP_ITERS[k], count, LOOP_ITERS[k]))

        if unrolled:
            if unrolled.cstring:
                w('string_size := decode_array_size_unchecked(d)')
                size = 'string_size'
            else:
                w('array_size := decode_array_size(d, %s)' % unrolled.count)
                size = 'array_size'
            if is_ptr:
                k = len(levels)
                if var.is_blob():
                    alloc = 'd.AllocTemp(uintptr(%s))' % size
                else:
                    alloc = 'd.AllocTempArray(%s, %s)' % (self.elem_size_at(var, k), size)
                container = allocate(k, alloc)
            if validity != VI.INVALID:
                w('decode_%s_array(d, %s, %s)' % (self.array_stem(var), container, size))
        elif not levels:
            if is_ptr:
                container = allocate(0, 'd.AllocTemp(%s)' % self.elem_size(var.ty.base))
            if validity != VI.INVALID:
                w(self.decode_call(var, validity, container))
        else:
            k = len(levels) - 1
            if validity != VI.INVALID:
                addr = 'elem(%s, %s, %s)' % (container, LOOP_ITERS[k], self.elem_size_at(var, k))
                w(self.decode_call(var, validity, addr))

        for _ in levels:
            w('}')

    # Encoding.

    def encode_call(self, var, cont, addr):
        VkType = self.VkType
        base = var.ty.base
        if base.category == VkType.HANDLE:
            return 'encode_uint64_t(e, %s)' % addr
        if base.category in (VkType.STRUCT, VkType.UNION):
            if 'selector' in var.attrs:
                sel = [v for v in cont.ty.variables if v.name == var.attrs['selector']][0]
                return 'encode_%s(e, %s, int32(%s))' % (base.name, addr, cont.field(sel))
            return 'encode_%s(e, %s)' % (base.name, addr)
        return 'encode_%s(e, %s)' % (self.prim(base), addr)

    def encode_var(self, w, ty, var, cont):
        """Emits the encoding of a member or reply, as
        Gen._encode_variable_info and Gen._encode_variable do for a valid
        variable."""
        assert 'stride' not in var.attrs, (ty.name, var.name)
        is_ptr = var.ty.is_pointer()
        body = Writer()
        if not self.gen.is_serializable(var):
            body('e.SetFatal()')
        else:
            self.encode_body(body, ty, var, cont)
        if var.is_dynamic_array():
            w('if %s != nil {' % cont.value(var))
            w.extend(body)
            w('} else {')
            w('encode_array_size(e, 0)')
            w('}')
        elif is_ptr:
            w('if encode_simple_pointer(e, %s) {' % cont.value(var))
            w.extend(body)
            w('}')
        elif len(body.lines) > 1:
            w('{')
            w.extend(body)
            w('}')
        else:
            w.extend(body)

    def encode_body(self, w, ty, var, cont):
        is_ptr = var.ty.is_pointer()
        levels, _ = self.levels(ty, var, cont)
        unrolled = self.unroll(var, levels)
        container = cont.value(var) if is_ptr else cont.addr(var)
        for k, lvl in enumerate(levels):
            assert not lvl.cstring
            if k > 0:
                c = 'c%d' % k
                w('%s := loadPointer(elem(%s, %s, 8))' % (c, container, LOOP_ITERS[k - 1]))
                container = c
            count = 'iter_count' if k == 0 else 'iter_count_' + LOOP_ITERS[k]
            w('%s := uint64(%s)' % (count, lvl.count))
            w('encode_array_size(e, %s)' % count)
            w('for %s := uint64(0); %s < %s; %s++ {' % (LOOP_ITERS[k], LOOP_ITERS[k], count, LOOP_ITERS[k]))
        if unrolled:
            if levels:
                k = len(levels)
                c = 'c%d' % k
                w('%s := loadPointer(elem(%s, %s, 8))' % (c, container, LOOP_ITERS[k - 1]))
                container = c
            if unrolled.cstring:
                w('string_size := cstrlen(%s) + 1' % container)
                size = 'string_size'
            else:
                w('array_size := uint64(%s)' % unrolled.count)
                size = 'array_size'
            w('encode_array_size(e, %s)' % size)
            w('encode_%s_array(e, %s, %s)' % (self.array_stem(var), container, size))
        elif not levels:
            w(self.encode_call(var, cont, container))
        else:
            k = len(levels) - 1
            w(self.encode_call(var, cont, 'elem(%s, %s, %s)' % (
                container, LOOP_ITERS[k], self.elem_size_at(var, k))))
        for _ in levels:
            w('}')

    # Replacing handles.

    def replace_call(self, var, cont, addr):
        VkType = self.VkType
        base = var.ty.base
        if base.category == VkType.HANDLE:
            return 'r.hostHandle(%s, %s)' % (addr, self.objtype(base))
        if 'selector' in var.attrs:
            sel = [v for v in cont.ty.variables if v.name == var.attrs['selector']][0]
            return 'replace_%s_handle(r, %s, int32(%s))' % (base.name, addr, cont.field(sel))
        return 'replace_%s_handle(r, %s)' % (base.name, addr)

    def replace_var(self, w, ty, var, cont, validity):
        """Emits the replacement of handles of a member or argument, as
        Gen._replace_variable_handle_info and Gen._replace_variable_handle
        do."""
        VI = self.vp.Gen.VariableInfo
        if (validity != VI.VALID or not var.ty.base.might_contain_handle() or
                not self.gen.is_serializable(var) or not self.needs_replace(var.ty.base)):
            return
        is_ptr = var.ty.is_pointer()
        levels, _ = self.levels(ty, var, cont)
        body = Writer()
        container = cont.value(var) if is_ptr else cont.addr(var)
        for k, lvl in enumerate(levels):
            if k > 0:
                c = 'c%d' % k
                body('%s := loadPointer(elem(%s, %s, 8))' % (c, container, LOOP_ITERS[k - 1]))
                container = c
            body('for %s, n := uint64(0), uint64(%s); %s < n; %s++ {' % (
                LOOP_ITERS[k], lvl.count, LOOP_ITERS[k], LOOP_ITERS[k]))
        if not levels:
            body(self.replace_call(var, cont, container))
        else:
            k = len(levels) - 1
            body(self.replace_call(var, cont, 'elem(%s, %s, %s)' % (
                container, LOOP_ITERS[k], self.elem_size_at(var, k))))
        for _ in levels:
            body('}')
        if is_ptr:
            w('if %s != nil {' % cont.value(var))
            w.extend(body)
            w('}')
        else:
            w.extend(body)

    # Types.

    def typed_func(self, w, signature, typed, ty_name, body):
        """Emits a function whose body uses a typed pointer to val if it
        needs it."""
        w(signature + ' {')
        text = '\n'.join(body.lines)
        if typed and re.search(r'\b%s\.' % typed, text):
            w('%s := (*%s)(val)' % (typed, ty_name))
        w.extend(body)
        w('}')
        w()

    def struct_funcs(self, w, ty):
        attrs = ty.attrs
        VkType = self.VkType
        if ty.category == VkType.UNION:
            if 'need_encode' in attrs:
                self.union_encode(w, ty)
            if 'need_decode' in attrs:
                self.union_decode(w, ty)
            if 'need_decode' in attrs and ty.might_contain_handle() and self.needs_replace(ty):
                self.union_replace(w, ty)
            return
        if 'need_encode' in attrs:
            self.struct_encode(w, ty)
        if 'need_decode' in attrs:
            self.struct_decode(w, ty, '')
        if 'need_partial' in attrs and ty.might_contain_handle():
            self.struct_decode(w, ty, '_partial')
        if 'need_decode' in attrs and ty.might_contain_handle():
            self.struct_replace(w, ty)

    def struct_members(self, ty, cont, skip):
        return ty.variables[2:] if skip and ty.s_type else ty.variables

    def struct_decode(self, w, ty, variant):
        VI = self.vp.Gen.VariableInfo
        partial = variant == '_partial'
        cont = Container(self, ty, 'v')
        if ty.s_type:
            next_types, _ = self.gen.get_chain(ty)
            w('func decode_%s_pnext%s_temp(d *Decoder) unsafe.Pointer {' % (ty.name, variant))
            if next_types:
                w('if !decode_simple_pointer(d) {')
                w('return nil')
                w('}')
                w('stype := decode_int32_value(d)')
                w('var pnext unsafe.Pointer')
                w('switch stype {')
                for n in next_types:
                    w('case %s:' % self.s_type(n))
                    w('pnext = d.AllocTemp(unsafe.Sizeof(%s{}))' % n.name)
                    w('if pnext != nil {')
                    w('setSType(pnext, stype)')
                    w('setPNext(pnext, decode_%s_pnext%s_temp(d))' % (ty.name, variant))
                    w('decode_%s_self%s_temp(d, pnext)' % (n.name, variant))
                    w('}')
                w('default:')
                w('d.SetFatal()')
                w('}')
                w('return pnext')
            else:
                w('if decode_simple_pointer(d) {')
                w('d.SetFatal()')
                w('}')
                w('return nil')
            w('}')
            w()
            body = Writer()
            for var in ty.variables[2:]:
                self.decode_var(body, ty, var, cont, self.validity(ty, var, not partial))
            self.typed_func(w, 'func decode_%s_self%s_temp(d *Decoder, val unsafe.Pointer)' % (ty.name, variant),
                            'v', ty.name, body)
            w('func decode_%s%s_temp(d *Decoder, val unsafe.Pointer) {' % (ty.name, variant))
            w('stype := decode_int32_value(d)')
            w('if stype != %s {' % self.s_type(ty))
            w('d.SetFatal()')
            w('}')
            w('setSType(val, stype)')
            w('setPNext(val, decode_%s_pnext%s_temp(d))' % (ty.name, variant))
            w('decode_%s_self%s_temp(d, val)' % (ty.name, variant))
            w('}')
            w()
            return
        body = Writer()
        for var in ty.variables:
            self.decode_var(body, ty, var, cont, self.validity(ty, var, not partial))
        self.typed_func(w, 'func decode_%s%s_temp(d *Decoder, val unsafe.Pointer)' % (ty.name, variant),
                        'v', ty.name, body)

    def struct_encode(self, w, ty):
        cont = Container(self, ty, 'v')
        if ty.s_type:
            next_types, _ = self.gen.get_chain(ty)
            w('func encode_%s_pnext(e *Encoder, val unsafe.Pointer) {' % ty.name)
            if next_types:
                w('for pnext := val; pnext != nil; pnext = getPNext(pnext) {')
                w('switch getSType(pnext) {')
                for n in next_types:
                    w('case %s:' % self.s_type(n))
                    w('encode_simple_pointer(e, pnext)')
                    w('encode_int32_t(e, pnext)')
                    w('encode_%s_pnext(e, getPNext(pnext))' % ty.name)
                    w('encode_%s_self(e, pnext)' % n.name)
                    w('return')
                w('}')
                w('}')
            w('encode_simple_pointer(e, nil)')
            w('}')
            w()
            body = Writer()
            for var in ty.variables[2:]:
                self.encode_var(body, ty, var, cont)
            self.typed_func(w, 'func encode_%s_self(e *Encoder, val unsafe.Pointer)' % ty.name, 'v', ty.name, body)
            w('func encode_%s(e *Encoder, val unsafe.Pointer) {' % ty.name)
            w('encode_int32_value(e, %s)' % self.s_type(ty))
            w('encode_%s_pnext(e, getPNext(val))' % ty.name)
            w('encode_%s_self(e, val)' % ty.name)
            w('}')
            w()
            return
        body = Writer()
        for var in ty.variables:
            self.encode_var(body, ty, var, cont)
        self.typed_func(w, 'func encode_%s(e *Encoder, val unsafe.Pointer)' % ty.name, 'v', ty.name, body)

    def struct_replace(self, w, ty):
        VI = self.vp.Gen.VariableInfo
        cont = Container(self, ty, 'v')
        if ty.s_type:
            if self.self_has_handles(ty):
                body = Writer()
                for var in ty.variables:
                    self.replace_var(body, ty, var, cont, VI.VALID)
                self.typed_func(w, 'func replace_%s_handle_self(r *Replacer, val unsafe.Pointer)' % ty.name,
                                'v', ty.name, body)
            if not self.needs_replace(ty):
                return
            next_types, _ = self.gen.get_chain(ty)
            chain = [n for n in [ty] + next_types if self.self_has_handles(n)]
            w('func replace_%s_handle(r *Replacer, val unsafe.Pointer) {' % ty.name)
            w('for pnext := val; pnext != nil; pnext = getPNext(pnext) {')
            w('switch getSType(pnext) {')
            for n in chain:
                w('case %s:' % self.s_type(n))
                w('replace_%s_handle_self(r, pnext)' % n.name)
            w('}')
            w('}')
            w('}')
            w()
            return
        if not self.needs_replace(ty):
            return
        body = Writer()
        for var in ty.variables:
            self.replace_var(body, ty, var, cont, VI.VALID)
        self.typed_func(w, 'func replace_%s_handle(r *Replacer, val unsafe.Pointer)' % ty.name, 'v', ty.name, body)

    def union_cases(self, ty):
        if ty.is_valid_union():
            return [(self.enum_value(s), s, var) for s, var in ty.get_union_cases()]
        return [(i, None, var) for i, var in ty.get_union_cases()]

    def union_decode(self, w, ty):
        VI = self.vp.Gen.VariableInfo
        cont = Container(self, ty, None)
        w('func decode_%s_temp(d *Decoder, val unsafe.Pointer) {' % ty.name)
        if ty.is_valid_union():
            w('tag := decode_int32_value(d)')
        else:
            w('tag := decode_uint32_value(d)')
        w('switch tag {')
        for value, name, var in self.union_cases(ty):
            w('case %d:%s' % (value, ' // ' + name if name else ''))
            self.decode_var(w, ty, var, cont, VI.VALID)
        w('default:')
        w('d.SetFatal()')
        w('}')
        w('}')
        w()

    def union_encode(self, w, ty):
        cont = Container(self, ty, None)
        if ty.is_valid_union():
            w('func encode_%s(e *Encoder, val unsafe.Pointer, tag int32) {' % ty.name)
            w('encode_int32_value(e, tag)')
        else:
            tag = self.vp.Gen.UNION_DEFAULT_TAGS[ty.name]
            w('func encode_%s(e *Encoder, val unsafe.Pointer) {' % ty.name)
            w('const tag = %d // the union has no selector' % tag)
            w('encode_uint32_value(e, tag)')
        w('switch tag {')
        for value, name, var in self.union_cases(ty):
            w('case %d:%s' % (value, ' // ' + name if name else ''))
            self.encode_var(w, ty, var, cont)
        w('default:')
        w('e.SetFatal()')
        w('}')
        w('}')
        w()

    def union_replace(self, w, ty):
        VI = self.vp.Gen.VariableInfo
        cont = Container(self, ty, None)
        w('func replace_%s_handle(r *Replacer, val unsafe.Pointer, tag int32) {' % ty.name)
        w('switch tag {')
        for value, name, var in self.union_cases(ty):
            body = Writer()
            self.replace_var(body, ty, var, cont, VI.VALID)
            if body.lines:
                w('case %d:%s' % (value, ' // ' + name if name else ''))
                w.extend(body)
        w('}')
        w('}')
        w()

    # Commands.

    def command_funcs(self, w, ty):
        cont = Container(self, ty, 'args')
        args_ty = 'Args_' + ty.name
        body = Writer()
        for var in ty.variables:
            validity = self.validity(ty, var, 'var_in' in var.attrs)
            self.decode_var(body, ty, var, cont, validity)
        self.typed_func(w, 'func decode_%s_args_temp(d *Decoder, val unsafe.Pointer)' % ty.name,
                        'args', args_ty, body)

        body = Writer()
        for var in ty.variables:
            validity = self.validity(ty, var, 'var_in' in var.attrs)
            self.replace_var(body, ty, var, cont, validity)
        if body.lines:
            self.typed_func(w, 'func replace_%s_args_handle(r *Replacer, val unsafe.Pointer)' % ty.name,
                            'args', args_ty, body)
            self.replaced_commands.add(ty.name)

        body = Writer()
        body('encode_int32_value(e, %d) // %s' % (self.enum_value(ty.attrs['c_type']), ty.attrs['c_type']))
        if ty.ret:
            self.encode_var(body, ty, ty.ret, cont)
        for var in ty.variables:
            if 'var_out' in var.attrs:
                self.encode_var(body, ty, var, cont)
        self.typed_func(w, 'func encode_%s_reply(e *Encoder, val unsafe.Pointer)' % ty.name,
                        'args', args_ty, body)

    def group_file(self, group):
        w = Writer()
        for ty in group.structs:
            self.struct_funcs(w, ty)
        for ty in group.commands:
            self.command_funcs(w, ty)
        return w


def godefs_upper(s):
    if s.startswith('_'):
        return 'X' + s
    return s[0].upper() + s[1:]


def godefs_prefix(names):
    """The prefix that cgo -godefs strips from the fields of a struct, as
    its fieldPrefix and godefsFields find it."""
    prefix = ''
    for n in names:
        if n.startswith('Pad_cgo_') or n.startswith('_'):
            continue
        i = n.find('_')
        if i < 0:
            continue
        if prefix == '':
            prefix = n[:i + 1]
        elif prefix != n[:i + 1]:
            return ''
    if prefix:
        seen = set()
        for n in names:
            if n == '_':
                continue
            if n != prefix and n.startswith(prefix):
                n = n[len(prefix):]
            n = godefs_upper(n)
            if n in seen:
                return ''
            seen.add(n)
    return prefix


def api_constants(vk_xml):
    consts = {}
    root = ET.parse(vk_xml).getroot()
    for enums in root.iterfind('enums'):
        if enums.attrib.get('type') != 'constants':
            continue
        for e in enums.iterfind('enum'):
            name = e.attrib['name']
            if 'value' in e.attrib:
                try:
                    consts[name] = int(e.attrib['value'], 0)
                except ValueError:
                    pass
        for e in enums.iterfind('enum'):
            if 'alias' in e.attrib and e.attrib['alias'] in consts:
                consts[e.attrib['name']] = consts[e.attrib['alias']]
    return consts


def run(cmd, **kwargs):
    return subprocess.run(cmd, check=True, **kwargs)


def go_types(out, vn_dir, vk_dir, struct_names, command_names, version, include_dir):
    """Writes vn/ztypes_unsafe.go, Go mirrors of C types, with cgo -godefs."""
    declared = list(struct_names)
    with tempfile.TemporaryDirectory() as tmp:
        for _ in range(8):
            src = ['package vn', '', '/*', '#include "vn_protocol_renderer_defines.h"', '*/',
                   'import "C"', '']
            for name in declared:
                src.append('type %s C.%s' % (name, name))
            for name in command_names:
                src.append('type Args_%s C.struct_vn_command_%s' % (name, name))
            path = os.path.join(tmp, 'types.go')
            with open(path, 'w') as f:
                f.write('\n'.join(src) + '\n')
            res = subprocess.run(['go', 'tool', 'cgo', '-godefs', '--', '-I' + str(vk_dir),
                                  '-I' + str(include_dir), path],
                                 cwd=tmp, capture_output=True, text=True)
            if res.returncode != 0:
                sys.exit('cgo -godefs failed:\n' + res.stderr)
            missing = sorted(set(re.findall(r'_Ctype_struct_(\w+)', res.stdout)) - set(declared))
            missing = [m for m in missing if not m.endswith('_T')]
            if not missing:
                break
            declared.extend(missing)
        else:
            sys.exit('cgo -godefs: unresolved types')

    lines = []
    for line in res.stdout.splitlines():
        if line.startswith('//') or line.startswith('package '):
            continue
        m = re.match(r'^(\t\w+\s+)(.+)$', line)
        if m:
            line = m.group(1) + go_field_type(m.group(2))
        lines.append(line)
    text = GO_HEADER.format(version=version) + 'package vn\n\nimport "unsafe"\n' + '\n'.join(lines) + '\n'
    path = vn_dir / 'ztypes_unsafe.go'
    path.write_text(text)


def go_field_type(t):
    m = re.fullmatch(r'(\[\d+\])?\*_Ctype_struct_(\w+)_T', t)
    if m:
        return (m.group(1) or '') + 'Handle'
    m = re.fullmatch(r'(\[\d+\])?\*.*', t)
    if m:
        return (m.group(1) or '') + 'unsafe.Pointer'
    return re.sub(r'_Ctype_struct_(\w+)', r'\1', t)


def c_headers(vp, gen, vk_dir, version, templates):
    """Writes the C headers that venus-protocol generates for virglrenderer
    and that the vk package needs."""
    loader = vp.TemplateLoader(templates)
    generators = vp.get_generators(gen)
    banner = '/* This file is generated by venus-protocol.  See vn_protocol_renderer.h. */\n\n'.encode()
    for cls, name in [(vp.GenDefines, 'renderer_defines.h'), (vp.GenInfo, 'renderer_info.h'),
                      (vp.GenUtil, 'renderer_util.h')]:
        out = generators[cls].generate(loader.get_template(name))
        (vk_dir / ('vn_protocol_' + name)).write_bytes(banner + out)
    (vk_dir / 'vn_protocol_renderer_cs.h').write_text(
        C_HEADER.format(version=version) +
        '#ifndef VN_PROTOCOL_RENDERER_CS_H\n'
        '#define VN_PROTOCOL_RENDERER_CS_H\n\n'
        '/* What venus-protocol\'s generated declarations need of a renderer\'s\n'
        ' * command streams: TTC\'s are Go\'s, which these do not use. */\n'
        '#include <assert.h>\n'
        '#include <stdbool.h>\n'
        '#include <stdint.h>\n\n'
        'struct vn_cs_encoder;\n'
        'struct vn_cs_decoder;\n\n'
        '#endif /* VN_PROTOCOL_RENDERER_CS_H */\n')
    return generators[vp.GenUtil]


def c_calls(util, gen, vk_dir, version, dispatched):
    """Writes vk/zcall.c: vn_call, which calls a command through a
    procedure table."""
    lines = [C_HEADER.format(version=version), '#include "zcall.h"', '',
             'bool vn_call(int32_t type, const void *table, void *args)', '{',
             '    switch (type) {']
    for kind, entries in [('global', util.global_commands), ('instance', util.instance_commands),
                          ('physical_device', util.physical_device_commands),
                          ('device', util.device_commands)]:
        for cmd, _, _ in sorted(entries, key=lambda e: e[0].name):
            if cmd.name not in dispatched:
                continue
            call_args = ', '.join('a->' + v.name for v in cmd.variables)
            call = 'vk->%s(%s)' % (cmd.name[2:], call_args)
            if cmd.ret:
                call = 'a->ret = ' + call
            lines += ['    case %s: {' % cmd.attrs['c_type'],
                      '        const struct vn_%s_proc_table *vk = table;' % kind,
                      '        struct vn_command_%s *a = args;' % cmd.name,
                      '        if (!vk->%s)' % cmd.name[2:],
                      '            return false;',
                      '        %s;' % call,
                      '        return true;',
                      '    }']
    lines += ['    default:', '        return false;', '    }', '}', '']
    (vk_dir / 'zcall.c').write_text('\n'.join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--venus-protocol', type=Path, required=True,
                        help='a checkout of venus-protocol')
    parser.add_argument('--out', type=Path, required=True,
                        help='runsc/ttc/gfxrenderer/venus')
    args = parser.parse_args()

    src = args.venus_protocol.resolve()
    sys.path.insert(0, str(src))
    import vn_protocol as vp
    from vkxml import VkType

    version = subprocess.run(['git', '-C', str(src), 'describe', '--tags', '--always'],
                             capture_output=True, text=True).stdout.strip() or 'unknown'
    vk_xml, private_xmls = vp.get_vk_xmls(src)
    reg = vp.VkRegistry.parse(vk_xml, private_xmls)
    gen = vp.Gen(False, reg)
    groups = vp.GenStructsAndCommands(gen)
    consts = api_constants(vk_xml)
    gg = GoGen(vp, VkType, gen, consts)

    args.out = args.out.resolve()
    vn_dir = args.out / 'vn'
    vk_dir = args.out / 'vk'
    vn_dir.mkdir(parents=True, exist_ok=True)
    vk_dir.mkdir(parents=True, exist_ok=True)

    # Vulkan's headers, as the model's vk.xml has them.
    include_dir = vk_dir / 'include'
    if include_dir.exists():
        shutil.rmtree(include_dir)
    (include_dir / 'vulkan').mkdir(parents=True)
    for name in ['vulkan.h', 'vk_platform.h', 'vulkan_core.h', 'vulkan_metal.h']:
        shutil.copy(src / 'include' / 'vulkan' / name, include_dir / 'vulkan' / name)
    shutil.copytree(src / 'include' / 'vk_video', include_dir / 'vk_video')

    util = c_headers(vp, gen, vk_dir, version, src / 'templates')

    # The protocol.
    for old in list(vn_dir.glob('zprotocol_*.go')) + list(vn_dir.glob('z*_unsafe.go')):
        old.unlink()
    struct_names = []
    commands = []
    for group in groups.groups:
        for ty in group.structs:
            struct_names.append(ty.name)
        commands.extend(group.commands)
        w = gg.group_file(group)
        if not w.lines:
            continue
        text = GO_HEADER.format(version=version) + 'package vn\n\nimport "unsafe"\n\n' + w.text()
        (vn_dir / ('zprotocol_%s_unsafe.go' % group.name)).write_text(text)
    for name in ['VkBaseInStructure', 'VkBaseOutStructure']:
        struct_names.append(name)

    commands.sort(key=lambda c: gg.enum_value(c.attrs['c_type']))
    dispatched = {c.name for c in commands}
    levels = {}
    for kind, entries in [('LevelGlobal', util.global_commands), ('LevelInstance', util.instance_commands),
                          ('LevelPhysicalDevice', util.physical_device_commands),
                          ('LevelDevice', util.device_commands)]:
        for cmd, _, _ in entries:
            levels[cmd.name] = kind

    w = Writer()
    w('// CommandTableSize is one more than the largest command type.')
    w('const CommandTableSize = %d' % (reg.max_vk_command_type_value + 1))
    w()
    w('var commandTable = [CommandTableSize]*Command{')
    for cmd in commands:
        flags = []
        if cmd.variables and cmd.variables[0].ty.base.category == VkType.HANDLE and \
                cmd.variables[0].ty.base.dispatchable:
            flags.append('cmdDispatchable')
        if cmd.can_device_lost:
            flags.append('cmdCanDeviceLost')
        if cmd.ret and cmd.ret.ty.name == 'VkResult':
            flags.append('cmdResult')
        VI = vp.Gen.VariableInfo
        if any(v.ty.base.category == VkType.HANDLE and
               gen._get_variable_validity(cmd, v, 'var_in' in v.attrs) == VI.PARTIAL
               for v in cmd.variables):
            flags.append('cmdCreates')
        if cmd.name.startswith(('vkDestroy', 'vkFree')):
            flags.append('cmdDestroys')
        replace = 'replace_%s_args_handle' % cmd.name if cmd.name in gg.replaced_commands else 'nil'
        w('%d: {' % gg.enum_value(cmd.attrs['c_type']))
        w('Name: "%s",' % cmd.name)
        w('Type: %d,' % gg.enum_value(cmd.attrs['c_type']))
        w('ArgsSize: unsafe.Sizeof(Args_%s{}),' % cmd.name)
        w('level: %s,' % levels.get(cmd.name, 'LevelNone'))
        if cmd.ret:
            w('ret: unsafe.Offsetof(Args_%s{}.Ret),' % cmd.name)
        w('flags: %s,' % (' | '.join(flags) or '0'))
        w('decode: decode_%s_args_temp,' % cmd.name)
        w('replace: %s,' % replace)
        w('encode: encode_%s_reply,' % cmd.name)
        w('},')
    w('}')
    text = GO_HEADER.format(version=version) + 'package vn\n\nimport "unsafe"\n\n' + w.text()
    (vn_dir / 'zcommands_unsafe.go').write_text(text)

    # Constants that the renderer uses.
    w = Writer()
    w('// Command types.')
    w('const (')
    for key, val in reg.type_table['VkCommandTypeEXT'].enums.values.items():
        w('%s = %s' % (key, val))
    w(')')
    w()
    for enum in ['VkResult', 'VkStructureType', 'VkObjectType']:
        w('// %s.' % enum)
        w('const (')
        for key in reg.type_table[enum].enums.values:
            w('%s = %d' % (key, gg.enum_value(key)))
        w(')')
        w()
    w('// API constants.')
    w('const (')
    for key, val in sorted(consts.items()):
        if val >= 0 and val < 1 << 31:
            w('%s = %d' % (key, val))
    w(')')
    text = GO_HEADER.format(version=version) + 'package vn\n\n' + w.text()
    (vn_dir / 'zconst.go').write_text(text)

    go_types(args.out, vn_dir, vk_dir, struct_names, [c.name for c in commands], version, include_dir)
    c_calls(util, gen, vk_dir, version, dispatched)

    run(['gofmt', '-w'] + [str(p) for p in vn_dir.glob('z*.go')])


if __name__ == '__main__':
    main()
