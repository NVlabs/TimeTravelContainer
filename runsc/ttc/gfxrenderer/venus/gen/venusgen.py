"""Generates TTC's renderer side of the Venus protocol.

venus-protocol (https://gitlab.freedesktop.org/virgl/venus-protocol) models
the protocol that Mesa's Venus Vulkan driver speaks, and generates from the
model the C encoders that Mesa uses and the C decoders that virglrenderer
uses. This generates, from the same model and by the same rules, what TTC's
renderer uses:

  vn/ztypes_unsafe.go   Go mirrors of the C structs that commands decode
                        into, from cgo -godefs;
  vn/zprotocol_*_unsafe.go
                        decoders, handle replacement, and reply encoders;
  vn/zcommands_unsafe.go
                        the table of commands;
  vn/zconst.go          constants;
  vk/vn_protocol_renderer_{cs,defines,info,util}.h
                        C declarations of venus-protocol's own types, of
                        commands' arguments, and of Vulkan's procedure
                        tables, as venus-protocol generates them;
  vk/zcall.c            a call of each command through the tables;
  vk/include            the Vulkan headers of the model's vk.xml.

Usage:

  venusgen.py --venus-protocol DIR --out runsc/ttc/gfxrenderer/venus

It needs Python's mako, as venus-protocol does, and Go.
"""

