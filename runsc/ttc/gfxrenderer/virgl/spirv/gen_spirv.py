"""Writes spirv_gen.go: SPIR-V's opcodes and enumerations, of Khronos's
grammar of SPIR-V (spirv.core.grammar.json), and GLSL.std.450's
instructions (GLSL.std.450.h), as SPIRV-Headers publishes them, and as Mesa
holds them in src/compiler/spirv.

Usage:
  gen_spirv.py GRAMMAR_JSON GLSL_STD_450_H | gofmt > spirv_gen.go
"""

import json
import re
import sys

# The enumerations that the package uses, by the grammar's kinds.
KINDS = [
    "Capability",
    "ExecutionModel",
    "AddressingModel",
    "MemoryModel",
    "ExecutionMode",
    "StorageClass",
    "Dim",
    "ImageFormat",
    "Decoration",
    "BuiltIn",
    "Scope",
    "MemorySemantics",
    "SelectionControl",
    "LoopControl",
    "FunctionControl",
    "ImageOperands",
    "MemoryAccess",
]


def go_name(s):
    return s[0].upper() + s[1:]


def main():
    grammar = json.load(open(sys.argv[1]))
    glsl = open(sys.argv[2]).read()
    out = []
    # The grammar's copyright, and its license's, which the header of
    # GLSL.std.450.h says too.
    holder = next(l for l in grammar["copyright"] if l.startswith("Copyright:"))[len("Copyright:"):].strip()
    spdx = next(l for l in grammar["copyright"] if l.startswith("License:"))[len("License:"):].strip()
    if f"SPDX-FileCopyrightText: {holder}" not in glsl or f"SPDX-License-Identifier: {spdx}" not in glsl:
        sys.exit("GLSL.std.450.h's copyright is not the grammar's")
    out.append(f"""// SPDX-FileCopyrightText: {holder}
// SPDX-License-Identifier: {spdx}

// SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.
// SPDX-License-Identifier: Apache-2.0

// Code generated by gen_spirv.py from the grammar of SPIR-V {grammar["major_version"]}.{grammar["minor_version"]}, revision {grammar["revision"]}, and GLSL.std.450.h. DO NOT EDIT.

package spirv

// Op is an instruction's opcode.
type Op uint16

// The opcodes.
const (""")
    seen = set()
    for inst in grammar["instructions"]:
        name = inst["opname"]
        if name in seen:
            continue
        seen.add(name)
        out.append(f"\t{name} Op = {inst['opcode']}")
    out.append(")\n")
    kinds = {k["kind"]: k for k in grammar["operand_kinds"]}
    for kind in KINDS:
        k = kinds[kind]
        out.append(f"// {kind} is SPIR-V's {kind}.")
        out.append(f"type {kind} uint32\n")
        out.append(f"// The values of {kind}.")
        out.append("const (")
        names = set()
        for e in k["enumerants"]:
            name = kind + go_name(e["enumerant"])
            if name in names:
                continue
            names.add(name)
            value = e["value"]
            if isinstance(value, str):
                value = int(value, 0)
            out.append(f"\t{name} {kind} = {value:#x}" if k["category"] == "BitEnum" else f"\t{name} {kind} = {value}")
        out.append(")\n")
    out.append("// GLSLstd450 is an instruction of the GLSL.std.450 extended instruction set.")
    out.append("type GLSLstd450 uint32\n")
    out.append("// The instructions of GLSL.std.450.")
    out.append("const (")
    for name, value in re.findall(r"\bGLSLstd450(\w+)\s*=\s*(\d+)", glsl):
        if name == "Count":
            continue
        out.append(f"\tGLSLstd450{name} GLSLstd450 = {value}")
    out.append(")")
    print("\n".join(out))


if __name__ == "__main__":
    main()
