"""Writes formats_gen.go: virgl's formats, as Vulkan's, of Mesa's tables.

virgl's formats are Gallium's (the renderer's virgl/formats.c maps them),
which Mesa's Vulkan utilities map from Vulkan's (vk_format.c), and whose
blocks and channels Mesa's u_format.yaml describes. Of the formats that
Vulkan lacks, Zink's rules (zink_format.c) emulate alpha, luminance,
intensity, and red-alpha formats by red ones, and formats of an unused
channel, X, by their alpha formats, with a swizzle that a view of the
format applies.

Usage:
  gen_formats.py MESA_SRC FORMATS_C | gofmt > formats_gen.go
"""

import re
import sys

import yaml

# The copyrights of the tables that the generated one is of.
HEADER = """// SPDX-FileCopyrightText: Copyright 2014, 2015 Red Hat.
// SPDX-FileCopyrightText: Copyright 2016 Intel Corporation
// SPDX-FileCopyrightText: Copyright 2019 Google LLC
// SPDX-License-Identifier: MIT

// SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.
// SPDX-License-Identifier: Apache-2.0

// Code generated by gen_formats.py from Mesa {version}'s format tables (virgl_hw.h,
// vk_format.c, u_format.yaml) and virgl/formats.c. DO NOT EDIT.

package vkgl
"""


def channel_bits(c):
    return int(re.sub(r"\D", "", c) or 0)


def main():
    mesa, formats_c = sys.argv[1], sys.argv[2]
    version = open(f"{mesa}/VERSION").read().strip()
    virgl = dict(re.findall(r"\[VIRGL_FORMAT_(\w+)\] = PIPE_FORMAT_(\w+)", open(formats_c).read()))
    hw = open(f"{mesa}/src/virtio/virtio-gpu/virgl_hw.h").read()
    virgl_values = {n: int(v) for n, v in re.findall(r"VIRGL_FORMAT_(\w+)\s*=\s*(\d+)", hw)}
    vk_map = {}
    for vk, pipe in re.findall(r"\[VK_FORMAT_(\w+)\] = PIPE_FORMAT_(\w+)",
                               open(f"{mesa}/src/vulkan/util/vk_format.c").read()):
        vk_map.setdefault(pipe, vk)
    core = open(f"{mesa}/include/vulkan/vulkan_core.h").read()
    vk_values = {n: int(v) for n, v in re.findall(r"\bVK_FORMAT_(\w+) = (\d+),", core)}
    desc = {f["name"]: f for f in yaml.safe_load(open(f"{mesa}/src/util/format/u_format.yaml"))}

    def emulated(p):
        """Returns the format that emulates p, and the swizzle of the
        emulation's channels that gives p's, of X, Y, Z, W, 0 and 1."""
        if p in vk_map:
            return p, "XYZW"
        if p not in desc:
            return None, None
        kind = None
        for prefix, k in (("A", "A"), ("L", "L"), ("I", "I")):
            if re.match(rf"^{prefix}\d+_", p):
                kind = k
        if re.match(r"^L\d+A\d+_", p):
            kind = "LA"
        elif re.match(r"^R\d+A\d+_", p):
            kind = "RA"
        if kind:
            bits = re.findall(r"\d+", p.split("_")[0])
            suffix = p.split("_", 1)[1]
            if kind in ("A", "L", "I"):
                e = f"R{bits[0]}_{suffix}"
                swizzle = {"A": "000X", "L": "XXX1", "I": "XXXX"}[kind]
            else:
                e = f"R{bits[0]}G{bits[1]}_{suffix}"
                swizzle = {"LA": "XXXY", "RA": "X00Y"}[kind]
            return (e, swizzle) if e in vk_map else (None, None)
        name = p.split("_")[0]
        if re.search(r"X\d+", name):
            # A format of an unused channel, as its format of alpha.
            e = re.sub(r"X(\d+)", r"A\1", name, count=1) + "_" + p.split("_", 1)[1]
            if e in vk_map:
                return e, "XYZ1"
        return None, None

    rows = []
    for name, pipe in sorted(virgl.items(), key=lambda kv: virgl_values[kv[0]]):
        e, swizzle = emulated(pipe)
        if e is None:
            continue
        d = desc[pipe]
        if "channels" not in d:
            # Of the little-endian layout, which the renderer's hosts have.
            d = dict(d, **d["little_endian"])
        block = d["block"]
        bits = sum(channel_bits(c) for c in d["channels"])
        if d["colorspace"] == "ZS":
            zs = [s for s in d["swizzles"][:2] if s != "_"]
            kind = "kindDepthStencil" if len(zs) == 2 else (
                "kindStencil" if "S8" in pipe and not pipe.startswith(("Z", "X")) else "kindDepth")
        else:
            # Of their channels but unused ones, X, which compressed
            # formats' are, whose texels are floats.
            used = [c for c in d["channels"] if not c.startswith("X")]
            kind = "kindFloat"
            if used and all(c.startswith("UP") for c in used):
                kind = "kindUint"
            elif used and all(c.startswith("SP") for c in used):
                kind = "kindSint"
        vk = vk_map[e]
        rows.append((virgl_values[name], name, vk, vk_values[vk], swizzle, bits // 8,
                     block["width"], block["height"], kind, d["colorspace"] == "SRGB",
                     d["layout"] not in ("plain", "other")))

    out = [HEADER.format(version=version)]
    out.append("// formats are virgl's formats that Vulkan has, or emulates, by their numbers.")
    out.append("var formats = map[uint32]Format{")
    for v, name, vk, vkv, swizzle, size, bw, bh, kind, srgb, compressed in rows:
        out.append(f'\t{v}: {{Name: "{name}", VK: {vkv}, Swizzle: "{swizzle}", BlockBytes: {size}, '
                   f'BlockWidth: {bw}, BlockHeight: {bh}, kind: {kind}, SRGB: {str(srgb).lower()}, '
                   f'Compressed: {str(compressed).lower()}}}, // VK_FORMAT_{vk}')
    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
