// imagegen converts the linked freestanding monitor Mach-O object into a Go
// byte array. It deliberately validates the final linked image instead of
// relying on individual object-file section ordering or unresolved relocs.
package main

import (
	"bufio"
	"debug/macho"
	"flag"
	"fmt"
	"os"
	"sort"
)

var requiredSymbols = map[string]string{
	"_ttc_monitor_bootstrap":               "embeddedMonitorBootstrapOffset",
	"_ttc_monitor_command_call":            "embeddedMonitorCommandCallOffset",
	"_ttc_monitor_command_entry":           "embeddedMonitorCommandOffset",
	"_ttc_monitor_ring0_application_entry": "embeddedMonitorRing0ApplicationOffset",
	"_ttc_monitor_vectors":                 "embeddedMonitorVectorOffset",
}

func main() {
	input := flag.String("input", "", "linked monitor Mach-O object")
	output := flag.String("output", "", "generated Go source")
	flag.Parse()
	if *input == "" || *output == "" {
		fatalf("-input and -output are required")
	}
	f, err := macho.Open(*input)
	if err != nil {
		fatalf("opening monitor object: %v", err)
	}
	defer f.Close()
	section := f.Section("__ttcmon")
	if section == nil || section.Seg != "__TEXT" || section.Size == 0 {
		fatalf("monitor object has no non-empty __TEXT,__ttcmon section")
	}
	if len(section.Relocs) != 0 {
		fatalf("monitor image retains %d relocations", len(section.Relocs))
	}
	for _, candidate := range f.Sections {
		if candidate != section && candidate.Size != 0 && candidate.Name != "__compact_unwind" {
			fatalf("monitor object has unexpected non-empty section %s,%s", candidate.Seg, candidate.Name)
		}
	}
	data, err := section.Data()
	if err != nil {
		fatalf("reading monitor section: %v", err)
	}
	if f.Symtab == nil {
		fatalf("monitor object has no symbol table")
	}
	offsets := make(map[string]uint64)
	for _, symbol := range f.Symtab.Syms {
		name, required := requiredSymbols[symbol.Name]
		if !required {
			continue
		}
		if symbol.Value < section.Addr || symbol.Value-section.Addr >= section.Size {
			fatalf("monitor symbol %s is outside __ttcmon", symbol.Name)
		}
		offsets[name] = symbol.Value - section.Addr
	}
	if len(offsets) != len(requiredSymbols) {
		fatalf("monitor object contains %d of %d required entry symbols", len(offsets), len(requiredSymbols))
	}
	out, err := os.Create(*output)
	if err != nil {
		fatalf("creating output: %v", err)
	}
	w := bufio.NewWriter(out)
	fmt.Fprintln(w, "// Code generated by monitor/imagegen; DO NOT EDIT.")
	fmt.Fprintln(w, "")
	fmt.Fprintln(w, "package hvf")
	fmt.Fprintln(w, "")
	fmt.Fprintln(w, "var embeddedMonitorImage = [...]byte{")
	for i, value := range data {
		if i%12 == 0 {
			fmt.Fprint(w, "\t")
		}
		fmt.Fprintf(w, "0x%02x,", value)
		if i%12 == 11 || i == len(data)-1 {
			fmt.Fprintln(w)
		} else {
			fmt.Fprint(w, " ")
		}
	}
	fmt.Fprintln(w, "}")
	names := make([]string, 0, len(offsets))
	for name := range offsets {
		names = append(names, name)
	}
	sort.Strings(names)
	fmt.Fprintln(w, "")
	fmt.Fprintln(w, "const (")
	for _, name := range names {
		fmt.Fprintf(w, "\t%s = uint64(%#x)\n", name, offsets[name])
	}
	fmt.Fprintln(w, ")")
	if err := w.Flush(); err != nil {
		fatalf("writing output: %v", err)
	}
	if err := out.Close(); err != nil {
		fatalf("closing output: %v", err)
	}
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "monitor imagegen: "+format+"\n", args...)
	os.Exit(1)
}
