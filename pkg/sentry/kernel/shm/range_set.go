package shm

import (
	"math"

	"gvisor.dev/gvisor/pkg/sentry/memmap"
	"gvisor.dev/gvisor/pkg/sentry/pgalloc"
)

// ShmFileRangeSet maps logical offsets in a SysV SHM segment to MemoryFile
// offsets.
//
// type ShmFileRangeSet <generated by go_generics>

// ShmFileRangeSetFunctions implements segment.Functions for ShmFileRangeSet.
type ShmFileRangeSetFunctions struct{}

func (ShmFileRangeSetFunctions) MinKey() uint64 { return 0 }

func (ShmFileRangeSetFunctions) MaxKey() uint64 { return math.MaxUint64 }

func (ShmFileRangeSetFunctions) ClearValue(_ *uint64) {}

func (ShmFileRangeSetFunctions) Merge(r1 memmap.MappableRange, frStart1 uint64, _ memmap.MappableRange, frStart2 uint64) (uint64, bool) {
	if frStart1+r1.Length() != frStart2 {
		return 0, false
	}
	return frStart1, true
}

func (ShmFileRangeSetFunctions) Split(r memmap.MappableRange, frStart, split uint64) (uint64, uint64) {
	return frStart, frStart + split - r.Start
}

// FileRange returns the MemoryFile range mapped by seg.
func (seg ShmFileRangeIterator) FileRange() memmap.FileRange {
	return seg.FileRangeOf(seg.Range())
}

// FileRangeOf returns the MemoryFile range mapped by mr.
func (seg ShmFileRangeIterator) FileRangeOf(mr memmap.MappableRange) memmap.FileRange {
	start := seg.Value() + mr.Start - seg.Start()
	return memmap.FileRange{Start: start, End: start + mr.Length()}
}

// DropAll releases every MemoryFile range owned by s and empties the set.
func (s *ShmFileRangeSet) DropAll(mf *pgalloc.MemoryFile) {
	for seg := s.FirstSegment(); seg.Ok(); seg = seg.NextSegment() {
		mf.DecRef(seg.FileRange())
	}
	s.RemoveAll()
}
